"""The reader's question-to-Reading snapshot cases (Phase 3, step 4, slice (c)).

Until slice (c) ``tests/query/test_router.py`` handed the stages a model-era
payload - an intent and slots - and asserted on the slot dict the stages
projected back. The parser's door takes a question with the names the
normalizer copied and its stat key, and returns the typed Reading; a case
here is that call, and its expected value is the typed record the stage
snapshot writes for a Reading (:func:`association.query.stages.read_stages`'s
``reading``), compared whole - the unit-test counterpart of the 2,710
readings population, for wordings the populations do not hold.

``reader_cases.json`` holds the cases: ``name``, ``why`` (the retired test's
reason, kept), ``question``, ``names`` (the model's spans), ``stat``, and
``expected``. A case whose record moves on purpose is regenerated by
``scripts/reader_cases.py`` with the move enumerated in the commit, as a
population baseline is.

The warehouse is the real ``players`` and ``teams`` tables, names and ids
alone (``tests/names``; a ``tests/data`` is caught by the repository's ``data/`` ignore pattern and never committed), so the names index reads a case exactly as
production does.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import duckdb

from association.query.entities import names_of
from association.query.parse import read_route
from association.query.reading import Reading
from association.query.stages import _reading_record

CASES = Path(__file__).parent / "query" / "reader_cases.json"

DATA = Path(__file__).parent / "names"
"""The warehouse's ``players`` (athlete_id, display_name) and ``teams``
(team_id, display_name, abbreviation) as the names index reads them -
every row, since a sampled index is not production's: on 65 of the 3,101
players "Curry" reached one man where the index holds two, and the
"Luther" in a holiday's name read as a surname the full index's own
dictionary rules out (54 of 430 cases differed, measured 2026-10-11)."""


def warehouse() -> duckdb.DuckDBPyConnection:
    """An in-memory warehouse holding the names the cases use."""
    con = duckdb.connect(":memory:")
    con.execute("CREATE TABLE players (athlete_id VARCHAR, display_name VARCHAR)")
    con.executemany("INSERT INTO players VALUES (?, ?)", json.loads((DATA / "players.json").read_text()))
    con.execute("CREATE TABLE teams (team_id VARCHAR, display_name VARCHAR, abbreviation VARCHAR)")
    con.executemany("INSERT INTO teams VALUES (?, ?, ?)", json.loads((DATA / "teams.json").read_text()))
    return con


def read(con: duckdb.DuckDBPyConnection, question: str, names: list[str] | None = None, stat: str = "") -> Reading:
    """The parser's door over the case warehouse."""
    return read_route(names_of(con), question, names, stat)


def record(reading: Reading) -> dict[str, Any]:
    """The Reading as the stage snapshot records it: the typed vocabulary,
    since Phase 3, step 4, slice (c) deleted the slot-era projection."""
    return _reading_record(reading, None)


def load_cases() -> list[dict[str, Any]]:
    """Every case, in file order."""
    return list(json.loads(CASES.read_text()))
